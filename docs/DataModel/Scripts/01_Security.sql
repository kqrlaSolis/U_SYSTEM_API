-- =====================================================================
-- U SYSTEM | Seguridad, roles, permisos y auditoría
-- Motor: MySQL 8.x | Tablas y columnas en PascalCase (inglés)
-- Regla del proyecto: solo los comentarios van en español
-- =====================================================================
USE USystem;

CREATE TABLE IF NOT EXISTS Users (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  FirstName VARCHAR(100) NOT NULL,
  PaternalLastName VARCHAR(100) NOT NULL,
  MaternalLastName VARCHAR(100) NULL,
  Email VARCHAR(150) NOT NULL,
  Username VARCHAR(50) NOT NULL,
  PasswordHash VARCHAR(255) NOT NULL,
  Phone VARCHAR(20) NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  MustChangePassword TINYINT(1) NOT NULL DEFAULT 1,
  FailedAttempts INT NOT NULL DEFAULT 0,
  LockedUntil DATETIME NULL,
  LastLoginAt DATETIME NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqUsersEmail (Email),
  UNIQUE KEY UqUsersUsername (Username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS RefreshTokens (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  UserId BIGINT NOT NULL,
  TokenHash VARCHAR(255) NOT NULL,
  ExpiresAt DATETIME NOT NULL,
  RevokedAt DATETIME NULL,
  IpAddress VARCHAR(45) NULL,
  UserAgent VARCHAR(255) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkRefreshTokensUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS PasswordResetTokens (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  UserId BIGINT NOT NULL,
  TokenHash VARCHAR(255) NOT NULL,
  ExpiresAt DATETIME NOT NULL,
  UsedAt DATETIME NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkPasswordResetTokensUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Roles (
  Id INT NOT NULL AUTO_INCREMENT,
  Name VARCHAR(80) NOT NULL,
  Description VARCHAR(255) NULL,
  IsSystem TINYINT(1) NOT NULL DEFAULT 0,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqRolesName (Name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Permissions (
  Id INT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(100) NOT NULL,
  Module VARCHAR(50) NOT NULL,
  Description VARCHAR(255) NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqPermissionsCode (Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS RolePermissions (
  RoleId INT NOT NULL,
  PermissionId INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (RoleId, PermissionId),
  CONSTRAINT FkRolePermissionsRoleId FOREIGN KEY (RoleId) REFERENCES Roles (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkRolePermissionsPermissionId FOREIGN KEY (PermissionId) REFERENCES Permissions (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS UserRoles (
  UserId BIGINT NOT NULL,
  RoleId INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (UserId, RoleId),
  CONSTRAINT FkUserRolesUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkUserRolesRoleId FOREIGN KEY (RoleId) REFERENCES Roles (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS AuditLogs (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  UserId BIGINT NULL,
  Action VARCHAR(50) NOT NULL,
  Module VARCHAR(50) NOT NULL,
  Entity VARCHAR(50) NOT NULL,
  EntityId VARCHAR(50) NULL,
  OldValue JSON NULL,
  NewValue JSON NULL,
  IpAddress VARCHAR(45) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  KEY IxAuditLogsModuleCreatedAt (Module, CreatedAt),
  CONSTRAINT FkAuditLogsUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
