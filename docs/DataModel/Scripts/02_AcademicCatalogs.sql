USE USystem;

CREATE TABLE IF NOT EXISTS Careers (
  Id INT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(20) NOT NULL,
  Name VARCHAR(150) NOT NULL,
  Level VARCHAR(30) NOT NULL,
  TermCount TINYINT NOT NULL,
  TotalCredits SMALLINT NOT NULL,
  Modality VARCHAR(20) NOT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqCareersCode (Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Subjects (
  Id INT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(20) NOT NULL,
  Name VARCHAR(150) NOT NULL,
  Credits TINYINT NOT NULL,
  TheoryHours TINYINT NOT NULL,
  PracticeHours TINYINT NOT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqSubjectsCode (Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS AcademicTerms (
  Id INT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(10) NOT NULL,
  Name VARCHAR(100) NOT NULL,
  AcademicYear SMALLINT NOT NULL,
  TermNumber TINYINT NOT NULL,
  StartDate DATE NOT NULL,
  EndDate DATE NOT NULL,
  EnrollmentStartDate DATE NOT NULL,
  EnrollmentEndDate DATE NOT NULL,
  ReEnrollmentStartDate DATE NOT NULL,
  ReEnrollmentEndDate DATE NOT NULL,
  ExamStartDate DATE NOT NULL,
  ExamEndDate DATE NOT NULL,
  GradeReportCloseDate DATE NOT NULL,
  Status VARCHAR(20) NOT NULL DEFAULT 'Planned',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqAcademicTermsCode (Code),
  KEY IxAcademicTermsStatus (Status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS StudyPlans (
  Id INT NOT NULL AUTO_INCREMENT,
  CareerId INT NOT NULL,
  Code VARCHAR(20) NOT NULL,
  Version VARCHAR(20) NOT NULL,
  StartDate DATE NOT NULL,
  EndDate DATE NULL,
  TotalCredits SMALLINT NOT NULL,
  IsCurrent TINYINT(1) NOT NULL DEFAULT 0,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqStudyPlansCareerCodeVersion (CareerId, Code, Version),
  CONSTRAINT FkStudyPlansCareerId FOREIGN KEY (CareerId) REFERENCES Careers (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS StudyPlanSubjects (
  StudyPlanId INT NOT NULL,
  SubjectId INT NOT NULL,
  TermNumber TINYINT NOT NULL,
  Type VARCHAR(20) NOT NULL DEFAULT 'Mandatory',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (StudyPlanId, SubjectId),
  CONSTRAINT FkStudyPlanSubjectsStudyPlanId FOREIGN KEY (StudyPlanId) REFERENCES StudyPlans (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudyPlanSubjectsSubjectId FOREIGN KEY (SubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS SubjectPrerequisites (
  StudyPlanId INT NOT NULL,
  SubjectId INT NOT NULL,
  PrerequisiteSubjectId INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (StudyPlanId, SubjectId, PrerequisiteSubjectId),
  CONSTRAINT FkSubjectPrerequisitesStudyPlanId FOREIGN KEY (StudyPlanId) REFERENCES StudyPlans (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkSubjectPrerequisitesSubjectId FOREIGN KEY (SubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkSubjectPrerequisitesPrerequisiteSubjectId FOREIGN KEY (PrerequisiteSubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS CourseMaterials (
  Id INT NOT NULL AUTO_INCREMENT,
  SubjectId INT NOT NULL,
  AcademicTermId INT NULL,
  Type VARCHAR(20) NOT NULL,
  Title VARCHAR(200) NOT NULL,
  Description TEXT NULL,
  Url VARCHAR(500) NULL,
  FilePath VARCHAR(500) NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkCourseMaterialsSubjectId FOREIGN KEY (SubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkCourseMaterialsAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
