USE USystem;

CREATE TABLE IF NOT EXISTS PaymentConcepts (
  Id INT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(20) NOT NULL,
  Name VARCHAR(150) NOT NULL,
  BaseAmount DECIMAL(12,2) NOT NULL,
  IsRecurring TINYINT(1) NOT NULL DEFAULT 0,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqPaymentConceptsCode (Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS PaymentPlans (
  Id INT NOT NULL AUTO_INCREMENT,
  CareerId INT NULL,
  AcademicTermId INT NOT NULL,
  Name VARCHAR(150) NOT NULL,
  InstallmentCount TINYINT NOT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkPaymentPlansCareerId FOREIGN KEY (CareerId) REFERENCES Careers (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkPaymentPlansAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Scholarships (
  Id INT NOT NULL AUTO_INCREMENT,
  Name VARCHAR(150) NOT NULL,
  Type VARCHAR(20) NOT NULL DEFAULT 'Percentage',
  Value DECIMAL(12,2) NOT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqScholarshipsName (Name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS StudentScholarships (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  ScholarshipId INT NOT NULL,
  AcademicTermId INT NOT NULL,
  AssignedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqStudentScholarshipsStudentTerm (StudentId, AcademicTermId),
  CONSTRAINT FkStudentScholarshipsStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentScholarshipsScholarshipId FOREIGN KEY (ScholarshipId) REFERENCES Scholarships (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentScholarshipsAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Charges (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  AcademicTermId INT NOT NULL,
  PaymentConceptId INT NOT NULL,
  Amount DECIMAL(12,2) NOT NULL,
  Discount DECIMAL(12,2) NOT NULL DEFAULT 0,
  Surcharge DECIMAL(12,2) NOT NULL DEFAULT 0,
  DueDate DATE NOT NULL,
  Status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  KEY IxChargesStudentStatus (StudentId, Status),
  KEY IxChargesDueDate (DueDate),
  CONSTRAINT FkChargesStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkChargesAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkChargesPaymentConceptId FOREIGN KEY (PaymentConceptId) REFERENCES PaymentConcepts (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Payments (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  ChargeId BIGINT NOT NULL,
  Amount DECIMAL(12,2) NOT NULL,
  Method VARCHAR(20) NOT NULL,
  Reference VARCHAR(100) NULL,
  PaymentDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ReceiptNumber VARCHAR(30) NOT NULL,
  UserId BIGINT NOT NULL,
  Status VARCHAR(20) NOT NULL DEFAULT 'Applied',
  CancelledAt DATETIME NULL,
  CancellationReason VARCHAR(255) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqPaymentsReceiptNumber (ReceiptNumber),
  CONSTRAINT FkPaymentsStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkPaymentsChargeId FOREIGN KEY (ChargeId) REFERENCES Charges (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkPaymentsUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
