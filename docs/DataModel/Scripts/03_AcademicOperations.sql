USE USystem;

CREATE TABLE IF NOT EXISTS Teachers (
  Id INT NOT NULL AUTO_INCREMENT,
  EmployeeNumber VARCHAR(20) NOT NULL,
  FirstName VARCHAR(100) NOT NULL,
  PaternalLastName VARCHAR(100) NOT NULL,
  MaternalLastName VARCHAR(100) NULL,
  Email VARCHAR(150) NOT NULL,
  Phone VARCHAR(20) NULL,
  Specialty VARCHAR(150) NULL,
  UserId BIGINT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqTeachersEmployeeNumber (EmployeeNumber),
  UNIQUE KEY UqTeachersEmail (Email),
  CONSTRAINT FkTeachersUserId FOREIGN KEY (UserId) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS TeacherSubjects (
  TeacherId INT NOT NULL,
  SubjectId INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (TeacherId, SubjectId),
  CONSTRAINT FkTeacherSubjectsTeacherId FOREIGN KEY (TeacherId) REFERENCES Teachers (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkTeacherSubjectsSubjectId FOREIGN KEY (SubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ClassGroups (
  Id INT NOT NULL AUTO_INCREMENT,
  AcademicTermId INT NOT NULL,
  SubjectId INT NOT NULL,
  TeacherId INT NOT NULL,
  Code VARCHAR(20) NOT NULL,
  Classroom VARCHAR(50) NULL,
  Capacity SMALLINT NOT NULL,
  EnrolledCount SMALLINT NOT NULL DEFAULT 0,
  Status VARCHAR(20) NOT NULL DEFAULT 'Open',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqClassGroupsTermCode (AcademicTermId, Code),
  CONSTRAINT FkClassGroupsAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkClassGroupsSubjectId FOREIGN KEY (SubjectId) REFERENCES Subjects (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkClassGroupsTeacherId FOREIGN KEY (TeacherId) REFERENCES Teachers (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ClassGroupSchedules (
  Id INT NOT NULL AUTO_INCREMENT,
  ClassGroupId INT NOT NULL,
  DayOfWeek TINYINT NOT NULL,
  StartTime TIME NOT NULL,
  EndTime TIME NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkClassGroupSchedulesClassGroupId FOREIGN KEY (ClassGroupId) REFERENCES ClassGroups (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Students (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentNumber VARCHAR(20) NOT NULL,
  CareerId INT NOT NULL,
  StudyPlanId INT NOT NULL,
  EnrollmentTermId INT NOT NULL,
  FirstName VARCHAR(100) NOT NULL,
  PaternalLastName VARCHAR(100) NOT NULL,
  MaternalLastName VARCHAR(100) NULL,
  Curp VARCHAR(18) NOT NULL,
  BirthDate DATE NOT NULL,
  Gender VARCHAR(20) NOT NULL,
  Email VARCHAR(150) NULL,
  Phone VARCHAR(20) NULL,
  AddressLine VARCHAR(200) NULL,
  City VARCHAR(100) NULL,
  State VARCHAR(100) NULL,
  PostalCode VARCHAR(10) NULL,
  Status VARCHAR(20) NOT NULL DEFAULT 'Applicant',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqStudentsStudentNumber (StudentNumber),
  UNIQUE KEY UqStudentsCurp (Curp),
  KEY IxStudentsFullName (PaternalLastName, MaternalLastName, FirstName),
  CONSTRAINT FkStudentsCareerId FOREIGN KEY (CareerId) REFERENCES Careers (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentsStudyPlanId FOREIGN KEY (StudyPlanId) REFERENCES StudyPlans (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentsEnrollmentTermId FOREIGN KEY (EnrollmentTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS StudentGuardians (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  FullName VARCHAR(150) NOT NULL,
  Relationship VARCHAR(50) NOT NULL,
  Phone VARCHAR(20) NULL,
  Email VARCHAR(150) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FkStudentGuardiansStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS DocumentTypes (
  Id INT NOT NULL AUTO_INCREMENT,
  Name VARCHAR(100) NOT NULL,
  IsMandatory TINYINT(1) NOT NULL DEFAULT 1,
  AppliesToLevel VARCHAR(30) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqDocumentTypesName (Name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS StudentDocuments (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  DocumentTypeId INT NOT NULL,
  Status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  FilePath VARCHAR(500) NULL,
  Notes VARCHAR(500) NULL,
  ValidatedBy BIGINT NULL,
  ValidatedAt DATETIME NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqStudentDocumentsStudentType (StudentId, DocumentTypeId),
  CONSTRAINT FkStudentDocumentsStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentDocumentsDocumentTypeId FOREIGN KEY (DocumentTypeId) REFERENCES DocumentTypes (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkStudentDocumentsValidatedBy FOREIGN KEY (ValidatedBy) REFERENCES Users (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Enrollments (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  StudentId BIGINT NOT NULL,
  AcademicTermId INT NOT NULL,
  CareerId INT NOT NULL,
  Type VARCHAR(20) NOT NULL DEFAULT 'Enrollment',
  Status VARCHAR(20) NOT NULL DEFAULT 'Active',
  Notes VARCHAR(500) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (Id),
  UNIQUE KEY UqEnrollmentsStudentTerm (StudentId, AcademicTermId),
  KEY IxEnrollmentsTermStatus (AcademicTermId, Status),
  CONSTRAINT FkEnrollmentsStudentId FOREIGN KEY (StudentId) REFERENCES Students (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkEnrollmentsAcademicTermId FOREIGN KEY (AcademicTermId) REFERENCES AcademicTerms (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkEnrollmentsCareerId FOREIGN KEY (CareerId) REFERENCES Careers (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS EnrollmentClassGroups (
  EnrollmentId BIGINT NOT NULL,
  ClassGroupId INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CreatedBy BIGINT NULL,
  UpdatedAt DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UpdatedBy BIGINT NULL,
  DeletedAt DATETIME NULL,
  PRIMARY KEY (EnrollmentId, ClassGroupId),
  CONSTRAINT FkEnrollmentClassGroupsEnrollmentId FOREIGN KEY (EnrollmentId) REFERENCES Enrollments (Id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT FkEnrollmentClassGroupsClassGroupId FOREIGN KEY (ClassGroupId) REFERENCES ClassGroups (Id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
